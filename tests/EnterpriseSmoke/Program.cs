void Check(bool success, string description)
{
    checks++;
    if (!success) failures.Add(description);
    Console.WriteLine($"{(success ? "OK" : "ERROR")}: {description}");
}
void StartServer(int port)
{
    var info = new ProcessStartInfo("dotnet") { WorkingDirectory = backDirectory, UseShellExecute = false, CreateNoWindow = true, RedirectStandardOutput = true, RedirectStandardError = true };
    info.ArgumentList.Add(Path.Combine(backDirectory, "bin", "Release", "net10.0", "back.dll"));
    info.ArgumentList.Add("--urls"); info.ArgumentList.Add($"http://localhost:{port}");
    info.Environment["ASPNETCORE_ENVIRONMENT"] = "Development";
    info.Environment["DATABASE_URL"] = connectionBuilder.ConnectionString;
    info.Environment.Remove("PORT");
    var process = Process.Start(info)!;
    process.OutputDataReceived += (_, data) => { if (data.Data?.Contains("fail:") == true) Console.WriteLine(data.Data); };
    process.ErrorDataReceived += (_, data) => { if (data.Data is not null) Console.WriteLine(data.Data); };
    process.BeginOutputReadLine(); process.BeginErrorReadLine(); processes.Add(process);
}
