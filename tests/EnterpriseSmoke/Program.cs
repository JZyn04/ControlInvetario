static async Task<JsonElement> OkJson(Task<HttpResponseMessage> request)
{
    using var response = await request;
    var text = await response.Content.ReadAsStringAsync();
    if (!response.IsSuccessStatusCode) throw new InvalidOperationException($"HTTP {(int)response.StatusCode}: {text}");
    return JsonDocument.Parse(text).RootElement.Clone();
}
async Task Ready(HttpClient client)
{
    for (var retry = 0; retry < 60; retry++)
    {
        if (processes.Any(process => process.HasExited)) throw new InvalidOperationException("El backend terminó durante el arranque.");
        try { if ((await client.GetAsync("/health")).IsSuccessStatusCode) return; } catch (HttpRequestException) { }
        await Task.Delay(500);
    }
    throw new TimeoutException("El backend no inició.");
}
